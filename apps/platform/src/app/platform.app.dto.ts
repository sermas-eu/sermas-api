export class PlatformAppDto {
  // @IsUUID('4')
  @ApiProperty()
  appId: string;

  @ApiPropertyOptional()
  @IsOptional()
  public?: boolean;

  @IsString()
  @Transform((params: TransformFnParams) => sanitizeHtml(params.value))
  @ApiProperty()
  name: string;

  @IsString()
  @IsOptional()
  @Transform((params: TransformFnParams) => sanitizeHtml(params.value))
  @ApiProperty()
  description?: string;

  // @IsUUID('4')
  @ApiProperty({
    description: 'Owner of the application',
  })
  ownerId: string;

  @IsArray()
  @ValidateNested()
  @ApiProperty({
    type: [AppModuleConfigDto],
  })
  modules: AppModuleConfigDto[];

  @ApiProperty()
  repository: RepositoryConfigDto;

  @ValidateNested()
  @ApiProperty({
    type: [AppClientDto],
  })
  clients: AppClientDto[];

  @IsOptional()
  @ApiPropertyOptional()
  settings?: AppSettingsDto;

  @IsOptional()
  @IsDateString()
  @ApiPropertyOptional()
  createdAt?: Date;

  @IsOptional()
  @IsDateString()
  @ApiPropertyOptional()
  updatedAt?: Date;

  @ApiPropertyOptional({
    description: 'Application tools offered by the application',
    type: [AppToolsDTO],
  })
  @IsOptional()
  tools: AppToolsDTO[];

  @ApiPropertyOptional({
    description: 'Structured tasks offered by the application',
    type: [DialogueTaskDto],
  })
  @IsOptional()
  tasks: DialogueTaskDto[];
}

